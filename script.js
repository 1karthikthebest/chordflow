/* =====================================================
   MICROPHONE
===================================================== */

async function requestMicrophone() {

  try {

    const stream =
      await navigator.mediaDevices
        .getUserMedia({
          audio: true
        });


    mediaRecorder =
      new MediaRecorder(stream);


    audioChunks = [];


    mediaRecorder.ondataavailable =
      event => {

        if (event.data.size > 0) {

          audioChunks.push(
            event.data
          );

        }

      };


    mediaRecorder.onstop = () => {

      audioBlob =
        new Blob(
          audioChunks,
          {
            type:
              mediaRecorder.mimeType ||
              "audio/webm"
          }
        );


      const audioURL =
        URL.createObjectURL(
          audioBlob
        );


      const audio =
        document.getElementById(
          "recordedAudio"
        );


      audio.src =
        audioURL;


      audio.style.display =
        "block";


      document.getElementById(
        "downloadRecording"
      ).style.display =
        "inline-flex";


      document.getElementById(
        "deleteRecording"
      ).style.display =
        "inline-flex";

    };


    return true;

  } catch (error) {

    console.error(
      "Microphone error:",
      error
    );


    alert(
      "🎤 Microphone permission is required to record."
    );


    return false;
  }
}


/* =====================================================
   RECORDING
===================================================== */

async function toggleRecording() {

  const recordButton =
    document.getElementById(
      "recordButton"
    );


  /*
    First click:
    Ask for microphone permission.
  */

  if (!mediaRecorder) {

    const allowed =
      await requestMicrophone();


    if (!allowed) {
      return;
    }

  }


  /*
    START RECORDING
  */

  if (
    mediaRecorder.state ===
    "inactive"
  ) {

    audioChunks = [];


    mediaRecorder.start();


    recordingSeconds = 0;


    updateTimer();


    recordingTimer =
      setInterval(
        updateTimer,
        1000
      );


    recordButton.textContent =
      "⏹ Stop";


    recordButton.classList.add(
      "recording"
    );


    return;
  }


  /*
    STOP RECORDING
  */

  if (
    mediaRecorder.state ===
    "recording"
  ) {

    mediaRecorder.stop();


    clearInterval(
      recordingTimer
    );


    recordButton.textContent =
      "🎙 Record";


    recordButton.classList.remove(
      "recording"
    );

  }
}


/* =====================================================
   RECORDING TIMER
===================================================== */

function updateTimer() {

  const timer =
    document.getElementById(
      "recordingTimer"
    );


  const minutes =
    Math.floor(
      recordingSeconds / 60
    );


  const seconds =
    recordingSeconds % 60;


  timer.textContent =
    `${String(minutes).padStart(2, "0")}:${String(seconds).padStart(2, "0")}`;


  recordingSeconds++;
}


/* =====================================================
   DOWNLOAD RECORDING
===================================================== */

function downloadRecording() {

  if (!audioBlob) {

    alert(
      "No recording available."
    );

    return;
  }


  const url =
    URL.createObjectURL(
      audioBlob
    );


  const link =
    document.createElement(
      "a"
    );


  link.href = url;


  link.download =
    "KRIX-recording.webm";


  document.body.appendChild(
    link
  );


  link.click();


  link.remove();


  setTimeout(
    () => URL.revokeObjectURL(url),
    1000
  );
}


/* =====================================================
   DELETE RECORDING
===================================================== */

function deleteRecording() {

  audioBlob = null;


  const audio =
    document.getElementById(
      "recordedAudio"
    );


  audio.pause();


  audio.removeAttribute(
    "src"
  );


  audio.load();


  audio.style.display =
    "none";


  document.getElementById(
    "downloadRecording"
  ).style.display =
    "none";


  document.getElementById(
    "deleteRecording"
  ).style.display =
    "none";


  document.getElementById(
    "recordingTimer"
  ).textContent =
    "00:00";


  recordingSeconds = 0;
}


/* =====================================================
   HTML ESCAPE
===================================================== */

function escapeHtml(value) {

  return String(value)

    .replace(
      /&/g,
      "&amp;"
    )

    .replace(
      /</g,
      "&lt;"
    )

    .replace(
      />/g,
      "&gt;"
    )

    .replace(
      /"/g,
      "&quot;"
    )

    .replace(
      /'/g,
      "&#039;"
    );
}


