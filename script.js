async function generateSong() {

  const song =
    document.getElementById("songName")
      .value.trim();

  const artist =
    document.getElementById("artistName")
      .value.trim();

  const instrument =
    document.getElementById("instrument")
      .value;

  const lyrics =
    document.getElementById("lyricsInput")
      .value.trim();

  const status =
    document.getElementById(
      "generationStatus"
    );


  if (!song) {
    alert("Enter the song name.");
    return;
  }


  if (!artist) {
    alert("Enter the artist.");
    return;
  }


  status.textContent =
    "✨ KRIX is creating your music...";


  document.getElementById(
    "workspace"
  ).style.display = "block";


  document.getElementById(
    "outputSong"
  ).textContent = song;


  document.getElementById(
    "outputArtist"
  ).textContent = artist;


  const icons = {

    guitar: "🎸",
    piano: "🎹",
    flute: "🪈",
    ukulele: "🎵",
    violin: "🎻",
    keyboard: "🎹"

  };


  document.getElementById(
    "outputInstrument"
  ).textContent =

    `${icons[instrument]} ${
      instrument.charAt(0).toUpperCase()
      + instrument.slice(1)
    }`;


  document.getElementById(
    "sheetTitle"
  ).textContent = song;


  document.getElementById(
    "sheetArtist"
  ).textContent = artist;


  document.getElementById(
    "songContent"
  ).innerHTML = `

    <div class="empty-state">

      <div class="empty-icon">
        🪐
      </div>

      <p>
        KRIX is generating...
      </p>

    </div>

  `;


  try {

    const response =
      await fetch(
        "/api/generate",
        {

          method: "POST",

          headers: {
            "Content-Type":
              "application/json"
          },

          body: JSON.stringify({

            song: song,

            artist: artist,

            instrument: instrument,

            lyrics: lyrics

          })

        }
      );


    const data =
      await response.json();


    if (!response.ok) {

      throw new Error(
        data.error ||
        "KRIX generation failed."
      );
    }


    displaySong(data);


    status.textContent =
      "✅ Generated by KRIX";


  } catch (error) {

    console.error(error);


    document.getElementById(
      "songContent"
    ).innerHTML = `

      <div class="empty-state">

        <div class="empty-icon">
          ⚠️
        </div>

        <p>
          KRIX generation backend
          is not connected yet.
        </p>

        <p>
          Use Demo Mode to test
          the interface.
        </p>

      </div>

    `;


    status.textContent =
      "⚠️ KRIX backend unavailable.";
  }
}


/* =====================================================
   DISPLAY SONG
===================================================== */

function displaySong(data) {

  const content =
    document.getElementById(
      "songContent"
    );


  content.innerHTML = "";


  document.getElementById(
    "bpm"
  ).textContent =
    `${data.bpm || "--"} BPM`;


  document.getElementById(
    "sheetArtist"
  ).textContent =

    `${document.getElementById(
      "outputArtist"
    ).textContent} • Key: ${
      data.key || "Unknown"
    }`;


  if (
    !data.lines ||
    !Array.isArray(data.lines)
  ) {

    throw new Error(
      "Invalid KRIX response."
    );
  }


  data.lines.forEach(
    line => {

      const row =
        document.createElement(
          "div"
        );


      row.className =
        "song-line";


      row.innerHTML = `

        <div class="song-section">

          [${escapeHtml(
            line.section ||
            "Section"
          )}]

        </div>


        <div class="chords">

          ${escapeHtml(
            line.chords || ""
          )}

        </div>


        <div class="lyrics">

          ${escapeHtml(
            line.lyrics || ""
          )}

        </div>

      `;


      content.appendChild(row);

    }
  );


  transposeAmount = 0;


  document.getElementById(
    "transposeValue"
  ).textContent = "0";


  showMusicTab("chords");
}


/* =====================================================
   CHORDS / LYRICS
===================================================== */

function showMusicTab(type) {

  const chords =
    document.querySelectorAll(
      ".chords"
    );


  const lyrics =
    document.querySelectorAll(
      ".lyrics"
    );


  const chordsTab =
    document.getElementById(
      "chordsTab"
    );


  const lyricsTab =
    document.getElementById(
      "lyricsTab"
    );


  chordsTab.classList.remove(
    "active"
  );


  lyricsTab.classList.remove(
    "active"
  );


  if (type === "lyrics") {

    chords.forEach(
      item => {

        item.style.display =
          "none";

      }
    );


    lyrics.forEach(
      item => {

        item.style.display =
          "block";

      }
    );


    lyricsTab.classList.add(
      "active"
    );


  } else {

    /*
      Chords view shows both
      chords and lyrics.
    */

    chords.forEach(
      item => {

        item.style.display =
          "block";

      }
    );


    lyrics.forEach(
      item => {

        item.style.display =
          "block";

      }
    );


    chordsTab.classList.add(
      "active"
    );
  }
}


/* =====================================================
   TRANSPOSE
===================================================== */

const chordMap = {

  C: 0,
  "C#": 1,
  D: 2,
  "D#": 3,
  E: 4,
  F: 5,
  "F#": 6,
  G: 7,
  "G#": 8,
  A: 9,
  "A#": 10,
  B: 11

};


const chordNames = [

  "C",
  "C#",
  "D",
  "D#",
  "E",
  "F",
  "F#",
  "G",
  "G#",
  "A",
  "A#",
  "B"

];


function transposeChord(
  chord,
  amount
) {

  const match =
    chord.match(
      /^([A-G](?:#|b)?)(.*)$/
    );


  if (!match) {
    return chord;
  }


  let root =
    match[1];


  const rest =
    match[2];


  const flats = {

    Db: "C#",
    Eb: "D#",
    Gb: "F#",
    Ab: "G#",
    Bb: "A#"

  };


  if (root.includes("b")) {

    root =
      flats[root] || root;
  }


  if (!(root in chordMap)) {

    return chord;
  }


  let index =
    chordMap[root] + amount;


  index =
    ((index % 12) + 12) % 12;


  return (
    chordNames[index] +
    rest
  );
}


function transpose(amount) {

  transposeAmount += amount;


  document
    .querySelectorAll(".chords")
    .forEach(
      element => {

        const words =
          element.textContent
            .trim()
            .split(/\s+/);


        element.textContent =
          words
            .map(
              chord =>
                transposeChord(
                  chord,
                  amount
                )
            )
            .join(" ");

      }
    );


  document.getElementById(
    "transposeValue"
  ).textContent =

    transposeAmount > 0
      ? `+${transposeAmount}`
      : transposeAmount;
}


